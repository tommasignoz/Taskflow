import { drizzle } from 'drizzle-orm/postgres-js';
import postgres from 'postgres';
import * as schema from './schema.js';
import dotenv from 'dotenv';

dotenv.config();

const connectionString =
  process.env.DATABASE_URL || 'postgresql://postgres:postgres@localhost:5432/taskflow';

export const sqlClient = postgres(connectionString, {
  max: 10,
  idle_timeout: 20,
  connect_timeout: 10,
});

export const db = drizzle(sqlClient, { schema });

/**
 * Inizializza le tabelle tasks e Better Auth se non esistono già
 */
export async function initDatabase(): Promise<void> {
  // Tabella tasks
  await sqlClient`
    CREATE TABLE IF NOT EXISTS tasks (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      text TEXT NOT NULL,
      completed BOOLEAN NOT NULL DEFAULT FALSE,
      priority VARCHAR(20) NOT NULL DEFAULT 'media',
      created_at VARCHAR(30) NOT NULL,
      category VARCHAR(50) NOT NULL DEFAULT 'Generale',
      updated_at TIMESTAMPTZ DEFAULT NOW()
    );
  `;

  // Better Auth - Tabelle: user, session, account, verification
  await sqlClient`
    CREATE TABLE IF NOT EXISTS "user" (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      email_verified BOOLEAN NOT NULL DEFAULT FALSE,
      image TEXT,
      created_at TIMESTAMP NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMP NOT NULL DEFAULT NOW()
    );
  `;

  await sqlClient`
    CREATE TABLE IF NOT EXISTS "session" (
      id TEXT PRIMARY KEY,
      expires_at TIMESTAMP NOT NULL,
      token TEXT NOT NULL UNIQUE,
      created_at TIMESTAMP NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
      ip_address TEXT,
      user_agent TEXT,
      user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE
    );
  `;

  await sqlClient`
    CREATE INDEX IF NOT EXISTS "session_userId_idx" ON "session" (user_id);
  `;

  await sqlClient`
    CREATE TABLE IF NOT EXISTS "account" (
      id TEXT PRIMARY KEY,
      account_id TEXT NOT NULL,
      provider_id TEXT NOT NULL,
      user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
      access_token TEXT,
      refresh_token TEXT,
      id_token TEXT,
      access_token_expires_at TIMESTAMP,
      refresh_token_expires_at TIMESTAMP,
      scope TEXT,
      password TEXT,
      created_at TIMESTAMP NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMP NOT NULL DEFAULT NOW()
    );
  `;

  await sqlClient`
    CREATE INDEX IF NOT EXISTS "account_userId_idx" ON "account" (user_id);
  `;

  await sqlClient`
    CREATE TABLE IF NOT EXISTS "verification" (
      id TEXT PRIMARY KEY,
      identifier TEXT NOT NULL,
      value TEXT NOT NULL,
      expires_at TIMESTAMP NOT NULL,
      created_at TIMESTAMP NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMP NOT NULL DEFAULT NOW()
    );
  `;

  await sqlClient`
    CREATE INDEX IF NOT EXISTS "verification_identifier_idx" ON "verification" (identifier);
  `;
}

/**
 * Verifica la connessione a PostgreSQL
 */
export async function checkDbConnection(): Promise<boolean> {
  try {
    await sqlClient`SELECT 1`;
    return true;
  } catch (error) {
    console.error('❌ Impossibile connettersi a PostgreSQL:', error);
    return false;
  }
}
