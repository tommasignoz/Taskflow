import { drizzle } from 'drizzle-orm/postgres-js';
import postgres from 'postgres';
import * as schema from './schema.js';
import dotenv from 'dotenv';

dotenv.config();

const connectionString =
  process.env.DATABASE_URL || 'postgresql://postgres:postgres@localhost:5432/taskflow';

export const sqlClient = postgres(connectionString, {
  max: 10,
  idle_timeout: 20,
  connect_timeout: 10,
});

export const db = drizzle(sqlClient, { schema });

/**
 * Inizializza la tabella tasks se non esiste già
 */
export async function initDatabase(): Promise<void> {
  await sqlClient`
    CREATE TABLE IF NOT EXISTS tasks (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      text TEXT NOT NULL,
      completed BOOLEAN NOT NULL DEFAULT FALSE,
      priority VARCHAR(20) NOT NULL DEFAULT 'media',
      created_at VARCHAR(30) NOT NULL,
      category VARCHAR(50) NOT NULL DEFAULT 'Generale',
      updated_at TIMESTAMPTZ DEFAULT NOW()
    );
  `;
}

/**
 * Verifica la connessione a PostgreSQL
 */
export async function checkDbConnection(): Promise<boolean> {
  try {
    await sqlClient`SELECT 1`;
    return true;
  } catch (error) {
    console.error('❌ Impossibile connettersi a PostgreSQL:', error);
    return false;
  }
}
